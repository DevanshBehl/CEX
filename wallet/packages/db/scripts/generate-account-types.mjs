#!/usr/bin/env node
/**
 * Generate the account-type union and the Prisma enum from ACCOUNT_TYPES.
 *
 * An account type used to be written out by hand in four places, with eight
 * `CASE WHEN a.type = ...` arms downstream. A type added to the enum and missed
 * in a CASE arm is not a compile error — it is a balance that exists in the
 * ledger and does not appear in the query a user's balance is read from
 * (ADR-0032).
 *
 * This removes the copying. It does not remove the thinking: which tier a new
 * type belongs to is still a decision, and the balance tests are what prove it
 * was made.
 *
 *   node scripts/generate-account-types.mjs          # write
 *   node scripts/generate-account-types.mjs --check  # fail on drift (CI)
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const ACCOUNTS = resolve(here, '../../ledger/src/accounts.ts');
const ENTRIES = resolve(here, '../../ledger/src/entries.ts');
const UNION_OUT = resolve(here, '../src/account-types.generated.ts');
const SCHEMA = resolve(here, '../prisma/schema.prisma');

const check = process.argv.includes('--check');

/** Read a `export const NAME = [ ... ] as const;` string-literal array. */
function readConstArray(file, name) {
  const source = readFileSync(file, 'utf8');
  const match = source.match(new RegExp(`export const ${name} = \\[([\\s\\S]*?)\\] as const;`));
  if (!match) {
    throw new Error(`could not find ${name} in ${file}`);
  }
  // Quoted entries only, so doc comments between them are ignored.
  const values = [...match[1].matchAll(/^\s*'([a-z_]+)',/gm)].map((m) => m[1]);
  if (values.length === 0) {
    throw new Error(`${name} parsed as empty`);
  }
  return values;
}

function renderUnion(types, kinds) {
  return `// GENERATED by packages/db/scripts/generate-account-types.mjs — do not edit.
//
// The source is ACCOUNT_TYPES in packages/ledger/src/accounts.ts. Run
// \`pnpm --filter @wallet/db generate:account-types\` after changing it; CI
// fails on drift.
//
// \`packages/db\` does not import \`@wallet/ledger\` at runtime — the ledger is a
// pure domain package and this is its persistence layer, so the dependency is
// generated rather than taken.

export const LEDGER_ACCOUNT_TYPES = [
${types.map((t) => `  '${t}',`).join('\n')}
] as const;

export type LedgerAccountType = (typeof LEDGER_ACCOUNT_TYPES)[number];

// Source: TRANSACTION_KINDS in packages/ledger/src/entries.ts. The same
// four-copy problem as account types, fixed the same way.
export const LEDGER_TRANSACTION_KINDS = [
${kinds.map((k) => `  '${k}',`).join('\n')}
] as const;

export type LedgerTransactionKind = (typeof LEDGER_TRANSACTION_KINDS)[number];
`;
}

function replaceEnum(current, name, values) {
  const block = `enum ${name} {\n${values.map((v) => `  ${v}`).join('\n')}\n}`;
  const pattern = new RegExp(`enum ${name} \\{[^}]*\\}`);
  if (!pattern.test(current)) {
    throw new Error(`could not find enum ${name} in schema.prisma`);
  }
  return current.replace(pattern, block);
}

function renderSchema(current, types, kinds) {
  return replaceEnum(
    replaceEnum(current, 'LedgerAccountType', types),
    'LedgerTransactionKind',
    kinds,
  );
}

const types = readConstArray(ACCOUNTS, 'ACCOUNT_TYPES');
const kinds = readConstArray(ENTRIES, 'TRANSACTION_KINDS');
const union = renderUnion(types, kinds);
const schemaBefore = readFileSync(SCHEMA, 'utf8');
const schemaAfter = renderSchema(schemaBefore, types, kinds);

if (check) {
  const problems = [];
  let existingUnion = '';
  try {
    existingUnion = readFileSync(UNION_OUT, 'utf8');
  } catch {
    problems.push(`${UNION_OUT} is missing`);
  }
  if (existingUnion && existingUnion !== union) {
    problems.push('the generated account-type union is out of date');
  }
  if (schemaBefore !== schemaAfter) {
    problems.push(
      "schema.prisma's LedgerAccountType / LedgerTransactionKind do not match the ledger",
    );
  }
  if (problems.length > 0) {
    console.error('Account types have drifted from packages/ledger/src/accounts.ts:\n');
    for (const problem of problems) console.error(`  - ${problem}`);
    console.error('\nRun: pnpm --filter @wallet/db generate:account-types');
    process.exit(1);
  }
  console.log(`ledger enums are in sync (${types.length} account types, ${kinds.length} kinds)`);
} else {
  writeFileSync(UNION_OUT, union);
  writeFileSync(SCHEMA, schemaAfter);
  console.log(`generated ${types.length} account types and ${kinds.length} transaction kinds`);
}
