#!/usr/bin/env node
/**
 * Keep every state machine's database trigger identical to its TypeScript
 * transition table.
 *
 * `withdrawal-states.ts` has long carried a comment saying its `allTransitions()`
 * exists "to generate the database CHECK constraint, so the constraint and this
 * table cannot drift". Nothing ran it. The migration was written by hand, kept
 * honest only by an integration test (prompt_phase_s3.md rules 95-98).
 *
 * Applied migrations are immutable, so this does not rewrite them. It CHECKS:
 * for each machine it finds the LATEST migration that defines the trigger
 * function and asserts the legal pairs in that function are exactly the pairs
 * in the TypeScript table. A hand-edited constraint, or a table edited without
 * a new migration, fails the build.
 *
 *   node scripts/check-transition-constraints.mjs               # check (CI)
 *   node scripts/check-transition-constraints.mjs --emit order  # print SQL for a new migration
 */
import { readdirSync, readFileSync, existsSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
// Overridable so a test can point the check at a tampered copy and prove it fails.
const MIGRATIONS = process.env.TRANSITIONS_MIGRATIONS_DIR ?? resolve(here, '../prisma/migrations');
const TYPES = resolve(here, '../../types/src');

const MACHINES = {
  withdrawal: {
    source: resolve(TYPES, 'withdrawal-states.ts'),
    table: 'WITHDRAWAL_TRANSITIONS',
    fn: 'withdrawal_transition_is_legal',
    history: 'withdrawal_transitions',
    statusType: 'WithdrawalStatus',
  },
  order: {
    source: resolve(TYPES, 'order-states.ts'),
    table: 'ORDER_TRANSITIONS',
    fn: 'order_transition_is_legal',
    history: 'order_transitions',
    statusType: 'OrderStatus',
  },
};

/** Parse `export const NAME: ... = { A: ['B', 'C'], ... };` */
function readTable(file, name) {
  const source = readFileSync(file, 'utf8');
  const start = source.indexOf(`export const ${name}`);
  if (start < 0) throw new Error(`${name} not found in ${file}`);
  const open = source.indexOf('= {', start);
  const close = source.indexOf('\n};', open);
  const body = source.slice(open + 3, close);
  const pairs = [];
  for (const match of body.matchAll(/^\s*([A-Z_]+):\s*\[([^\]]*)\]/gm)) {
    for (const to of match[2].matchAll(/'([A-Z_]+)'/g)) pairs.push([match[1], to[1]]);
  }
  if (pairs.length === 0) throw new Error(`${name} parsed as having no transitions`);
  return pairs;
}

/** The legal pairs in the latest migration that defines `fn`. */
function readDeployed(fn) {
  if (!existsSync(MIGRATIONS)) return null;
  const dirs = readdirSync(MIGRATIONS, { withFileTypes: true })
    .filter((d) => d.isDirectory())
    .map((d) => d.name)
    .sort();
  let latest = null;
  for (const dir of dirs) {
    const sql = readFileSync(resolve(MIGRATIONS, dir, 'migration.sql'), 'utf8');
    const at = sql.indexOf(`CREATE OR REPLACE FUNCTION ${fn}()`);
    if (at >= 0) latest = { dir, sql: sql.slice(at, sql.indexOf('$$ LANGUAGE', at)) };
  }
  if (!latest) return null;
  const values = latest.sql.match(/FROM \(VALUES([\s\S]*?)\) AS t/);
  if (!values) throw new Error(`${fn} in ${latest.dir} has no VALUES list`);
  const pairs = [...values[1].matchAll(/\('([A-Z_]+)',\s*'([A-Z_]+)'\)/g)].map((m) => [m[1], m[2]]);
  return { dir: latest.dir, pairs };
}

function emit(name) {
  const m = MACHINES[name];
  const pairs = readTable(m.source, m.table);
  const values = pairs.map(([f, t]) => `    ('${f}', '${t}')`).join(',\n');
  return `-- BEGIN GENERATED by packages/db/scripts/check-transition-constraints.mjs --emit ${name}
-- Source: ${m.table} in packages/types/src/${name}-states.ts. Do not edit by hand;
-- CI compares this list against the TypeScript table.
CREATE OR REPLACE FUNCTION ${m.fn}()
RETURNS TRIGGER AS $$
DECLARE
  legal BOOLEAN;
BEGIN
  IF NEW.from_status IS NULL THEN
    RETURN NEW;
  END IF;

  SELECT EXISTS (
    SELECT 1 FROM (VALUES
${values}
    ) AS t(from_status, to_status)
    WHERE t.from_status = NEW.from_status::text
      AND t.to_status   = NEW.to_status::text
  ) INTO legal;

  IF NOT legal THEN
    RAISE EXCEPTION 'illegal ${name} transition % -> %', NEW.from_status, NEW.to_status
      USING ERRCODE = 'check_violation';
  END IF;

  RETURN NEW;
END;
$$ LANGUAGE plpgsql;
-- END GENERATED`;
}

const emitIndex = process.argv.indexOf('--emit');
if (emitIndex >= 0) {
  const name = process.argv[emitIndex + 1];
  if (!MACHINES[name]) throw new Error(`unknown machine: ${name}`);
  console.log(emit(name));
  process.exit(0);
}

const key = (pairs) => new Set(pairs.map(([f, t]) => `${f}->${t}`));
let failed = false;
for (const [name, m] of Object.entries(MACHINES)) {
  const declared = key(readTable(m.source, m.table));
  const deployed = readDeployed(m.fn);
  if (!deployed) {
    console.error(`✗ ${name}: no migration defines ${m.fn}()`);
    failed = true;
    continue;
  }
  const actual = key(deployed.pairs);
  const missing = [...declared].filter((p) => !actual.has(p));
  const extra = [...actual].filter((p) => !declared.has(p));
  if (missing.length || extra.length) {
    failed = true;
    console.error(`✗ ${name}: ${m.fn}() in ${deployed.dir} disagrees with ${m.table}`);
    for (const p of missing)
      console.error(`    legal in TypeScript, refused by the database: ${p}`);
    for (const p of extra)
      console.error(`    refused in TypeScript, allowed by the database: ${p}`);
  } else {
    console.log(`✓ ${name}: ${declared.size} transitions match ${deployed.dir}`);
  }
}
if (failed) {
  console.error('\nAdd a new migration containing the output of --emit <machine>.');
  process.exit(1);
}
